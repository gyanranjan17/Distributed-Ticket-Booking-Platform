-- 1. Event table
CREATE TABLE event (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       available_seats INTEGER,
                       name VARCHAR(255),
                       total_seats INTEGER,
                       venue VARCHAR(255)
);

-- 2. Shows table
CREATE TABLE shows (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       end_time TIMESTAMP(6) NOT NULL,
                       start_time TIMESTAMP(6) NOT NULL,
                       event_id BIGINT NOT NULL,

                       CONSTRAINT fk_shows_event
                           FOREIGN KEY (event_id)
                               REFERENCES event(id)
);

-- 3. Seats table
CREATE TABLE seats (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       row_label VARCHAR(255) NOT NULL,
                       seat_number VARCHAR(255) NOT NULL
);

-- 4. Show seats table
CREATE TABLE show_seats (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            price NUMERIC(10, 2) NOT NULL,
                            status VARCHAR(255) NOT NULL,
                            seat_id BIGINT NOT NULL,
                            show_id BIGINT NOT NULL,

                            CONSTRAINT uk_show_seat
                                UNIQUE (show_id, seat_id),

                            CONSTRAINT show_seats_status_check
                                CHECK (status IN ('AVAILABLE', 'LOCKED', 'BOOKED')),

                            CONSTRAINT fk_show_seats_show
                                FOREIGN KEY (show_id)
                                    REFERENCES shows(id),

                            CONSTRAINT fk_show_seats_seat
                                FOREIGN KEY (seat_id)
                                    REFERENCES seats(id)
);

-- 5. Bookings table
CREATE TABLE bookings (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          amount NUMERIC(10, 2) NOT NULL,
                          created_at TIMESTAMP(6) NOT NULL,
                          status VARCHAR(255) NOT NULL,
                          user_id BIGINT NOT NULL,
                          show_seat_id BIGINT NOT NULL,
                          expires_at TIMESTAMP(6),

                          CONSTRAINT bookings_status_check
                              CHECK (status IN (
                                                'PENDING',
                                                'CONFIRMED',
                                                'FAILED',
                                                'EXPIRED',
                                                'CANCELLED'
                                  )),

                          CONSTRAINT fk_bookings_show_seat
                              FOREIGN KEY (show_seat_id)
                                  REFERENCES show_seats(id)
);